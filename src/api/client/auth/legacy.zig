//! Legacy Auth.

const std = @import("std");

const common = @import("../common.zig");
const definitions = @import("../definitions.zig");

/// Gets the homeserver’s supported login types to authenticate users.
/// Clients should pick one of these and supply it as the type when
/// logging in.
///
/// https://spec.matrix.org/v1.19/client-server-api/#get_matrixclientv3login
///
/// # Errors
///
/// - `404` if the server does not support the legacy auth API.
/// - `429` if the request was rate-limited.
pub const LoginFlows = struct {
    pub const method: std.http.Method = .GET;
    pub const base: common.BaseKind = .homeserver;
    pub const path = "/_matrix/client/v3/login";
    pub const auth: common.Auth = .none;
    pub const added_in: ?common.SpecVersion = null;
    pub const rate_limited = true;

    pub const Path = void;
    pub const Query = void;
    pub const Body = void;
    pub const Response = struct {
        flows: []const LoginFlow,
    };

    pub const LoginFlow = struct {
        /// If type is `m.login.token`, an optional field to indicate to the
        /// unauthenticated client that the homeserver supports the
        /// POST /login/get_token endpoint. Note that supporting the
        /// endpoint does not necessarily indicate that the user
        /// attempting to log in will be able to generate such a token.
        get_login_token: ?bool = null,

        /// **Required:** The login type. This is supplied as the type
        /// when logging in.
        type: []const u8,

        pub const type_password = "m.login.password";
        pub const type_token = "m.login.token";
    };
};

/// Authenticates the user, and issues an access token they can
/// use to authorise themself in subsequent requests.
///
/// If the client does not supply a `device_id`, the server must
/// auto-generate one.
///
/// The returned access token must be associated with the `device_id`
/// supplied by the client or generated by the server. The server may
/// invalidate any access token previously associated with that device. See
/// [Relationship between access tokens and devices](https://spec.matrix.org/v1.19/client-server-api/#relationship-between-access-tokens-and-devices).
///
/// # Errors
///
/// - `400` if part of the request was invalid.
/// - `403` if the login attempt failed.
pub const Login = struct {
    pub const method: std.http.Method = .POST;
    pub const base: common.BaseKind = .homeserver;
    pub const path = "/_matrix/client/v3/login";
    pub const auth: common.Auth = .none;
    pub const added_in: ?common.SpecVersion = null;
    pub const rate_limited = true;

    pub const Path = void;
    pub const Query = void;
    pub const Body = struct {
        pub const flatten = "credentials";

        credentials: Credentials,
        device_id: ?[]const u8 = null,
        initial_device_display_name: ?[]const u8 = null,
        refresh_token: ?bool = null,

        pub fn jsonStringify(self: @This(), jws: anytype) !void {
            try common.stringify(self, jws);
        }
    };

    pub const Response = struct {
        user_id: []const u8,
        access_token: []const u8,
        device_id: []const u8,
        refresh_token: ?[]const u8,
        expires_in_ms: ?u64,
        well_known: ?definitions.DiscoveryInformation,
    };

    pub const Credentials = union(enum) {
        pub const type_prefix = "m.login.";

        password: struct {
            identifier: UserIdentifier,
            password: []const u8,
        },
        token: struct {
            token: []const u8,
        },
        application_service: struct {
            identifier: UserIdentifier,
        },
    };

    pub const UserIdentifier = union(enum) {
        pub const type_prefix = "m.id.";

        user: []const u8,
        thirdparty: struct {
            medium: []const u8,
            address: []const u8,
        },
        phone: struct {
            country: []const u8,
            phone: []const u8,
        },

        pub fn jsonStringify(self: @This(), jws: anytype) !void {
            try common.stringify(self, jws);
        }
    };
};

test "UserIdentifier json" {
    const gpa = std.testing.allocator;
    const cases = .{
        .{
            Login.UserIdentifier{ .user = "jacob" },
            \\{"type":"m.id.user","user":"jacob"}
        },
        .{
            Login.UserIdentifier{ .thirdparty = .{ .medium = "email", .address = "a@b.c" } },
            \\{"type":"m.id.thirdparty","medium":"email","address":"a@b.c"}
        },
        .{
            Login.UserIdentifier{ .phone = .{ .country = "GB", .phone = "0123" } },
            \\{"type":"m.id.phone","country":"GB","phone":"0123"}
        },
    };
    inline for (cases) |c| {
        const out = try std.json.Stringify.valueAlloc(gpa, c[0], common.serialise_options);
        defer gpa.free(out);
        try std.testing.expectEqualStrings(c[1], out);
    }
}

test "Login.Body json" {
    const gpa = std.testing.allocator;
    const body = Login.Body{
        .credentials = .{
            .password = .{
                .identifier = .{ .user = "jacob" },
                .password = "password123",
            },
        },
        .device_id = "ABC",
    };
    const out = try std.json.Stringify.valueAlloc(gpa, body, common.serialise_options);
    defer gpa.free(out);
    try std.testing.expectEqualStrings(
        \\{"device_id":"ABC","type":"m.login.password","identifier":{"type":"m.id.user","user":"jacob"},"password":"password123"}
    , out);
}

